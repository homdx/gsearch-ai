# аккордеон), который нужно раскрыть, чтобы увидеть больше деталей.
# Реальный случай (тема "бонусы Аэрофлота"): vision сам увидел "Условия
# получения премий" с стрелкой вниз (выпадающий список), но пайплайн на
# этом останавливался, не пытаясь его открыть.
