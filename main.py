def extract_main_page_text(html: str) -> str:
    """Достаёт ОСНОВНОЙ текст страницы ЦЕЛИКОМ, без обрезки (а не
    узкие фрагменты по плотности ключевых слов, как find_bonus_blocks).
    Обрезка под конкретный бюджет контекста происходит ОТДЕЛЬНО, в
    try_full_page_text(), с учётом реального лимита клиента - здесь
    просто извлекаем весь текст, сколько бы его ни было.

    Реальный случай: все 5 кандидатов от find_bonus_blocks оказались
    навигационными элементами (меню, реклама), а сам текст новости с
    искомым числом был в обычном параграфе статьи, который просто не
    попал в узкую выборку кандидатов - при этом текст был ПРЯМО НА
    СТРАНИЦЕ, и полный проход по нему нашёл бы ответ без vision вообще.

    Предпочитает <article>/<main>, если они есть (там обычно и лежит
    сама статья/контент, без меню и рекламы) - иначе берёт <body>
    целиком, вычищая <script>/<style>/<nav>/<header>/<footer>."""
    soup = BeautifulSoup(html, "html.parser")

    container = soup.find("article") or soup.find("main")
    if container is None:
        container = soup.find("body") or soup
        for tag in container.find_all(["script", "style", "nav", "header", "footer"]):
            tag.decompose()

    return container.get_text(separator=" ", strip=True)


def split_text_into_chunks(text: str, chunk_size: int, overlap: int = 200) -> list:
    """Режет длинный текст на части по chunk_size символов с небольшим
    перекрытием (overlap) между соседними частями - чтобы ответ,
    оказавшийся ровно на границе разреза, не потерялся полностью в
    обоих кусках. Возвращает список строк.

    БАГ (был): если overlap >= chunk_size, "start" на каждой итерации
    не продвигался вперёд (или даже двигался назад) - цикл уходил в
    бесконечное повторение при малом бюджете контекста. Теперь overlap
    всегда меньше chunk_size, и шаг вперёд гарантированно положителен."""
    if len(text) <= chunk_size:
        return [text]
    chunk_size = max(chunk_size, 1)
    overlap = min(overlap, chunk_size // 2)  # overlap не может "съесть" весь шаг вперёд
    step = max(chunk_size - overlap, 1)  # гарантированно положительный шаг

    chunks = []
    start = 0
    while start < len(text):
        end = start + chunk_size
        chunks.append(text[start:end])
        start += step
    return chunks


MAX_TEXT_CHUNKS = 5  # не более 5 заходов в LLM на одну страницу - защита от неограниченного числа запросов на очень длинных страницах


def extract_numbers(text: str) -> set:
    """Достаёт все числовые последовательности из текста (включая
    десятичные с точкой/запятой) - используется для грубой проверки
    "заземления" ответа модели в исходном тексте."""
    return set(re.findall(r"\d+(?:[.,]\d+)?", text))


def answer_numbers_grounded_in_source(answer: str, source_text: str) -> bool:
    """Подстраховка от галлюцинации цифр: проверяет, что числа,
    упомянутые в ответе модели, БУКВАЛЬНО встречаются в исходном
    тексте страницы, а не придуманы моделью "для правдоподобия".

    Реальный случай: модель ответила "high of 28°C and a low of 19°C"
    для конкретной будущей даты, хотя в тексте страницы таких цифр не
    было вообще (это была её собственная "оценка" по общим знаниям о
    климате) - валидатор в конце это поймал, но только после того, как
    ответ уже был принят как "достаточный" и остановил перебор других
    сайтов из выдачи. Эта проверка - более дешёвый и быстрый способ
    поймать явную выдумку чисел ДО того, как ответ будет принят как
    финальный, не дожидаясь дорогого прогона валидатора в конце.

    Не идеальна (проверяет только цифры, не факты в целом), но ловит
    самый частый и опасный тип галлюцинации - придуманные конкретные
    значения (температуры, количества, суммы и т.п.)."""
    answer_numbers = extract_numbers(answer)
    if not answer_numbers:
        return True  # ответ без чисел - эта проверка неприменима, не блокируем
    source_numbers = extract_numbers(source_text)
    # Требуем, чтобы хотя бы половина чисел из ответа встречалась в
    # источнике буквально - не 100%, т.к. в ответе могут быть суммы/
    # разности, посчитанные из нескольких чисел источника (это не
    # выдумка, а корректная арифметика над реальными данными).
    matched = answer_numbers & source_numbers
    return len(matched) >= max(1, len(answer_numbers) // 2)


def try_best_effort_answer(client: LLMClient, page_text: str, topic: str) -> str:
    """Мягкий гейт ПОСЛЕ строгой проверки - см. комментарий у
    BEST_EFFORT_SYSTEM. Один заход (не многопроходный, т.к. вызывается
    только на уже отфильтрованном непустом тексте после строгой
    проверки - если строгая проверка прошла по всем кускам без успеха,
    берём тот же текст целиком с уже известным бюджетом).

    БАГ (был): не передавались disable_reasoning/ограничение докрутки -
    reasoning-модель (nemotron) тратила весь max_tokens=300 на
    "reasoning"-поле, а при обрыве и попытке докрутки (по умолчанию
    max_continuations=2) впадала в мета-растерянность ("Wait, I don't
    have memory of previous interactions... this is a contradiction")
    вместо того чтобы просто дописать ответ - реальный случай: 3
    попытки подряд, ни одна не дошла до формата "ЛУЧШИЙ ДОСТУПНЫЙ
    ОТВЕТ", весь мягкий гейт (30+ секунд) оказался бесполезен, и
    скрипт всё равно ушёл в vision. disable_reasoning убирает лишний
    расход токенов на служебное поле, max_continuations=1 ограничивает
    число тупиковых повторов (эмпирически у этой модели вторая-третья
    докрутка только ухудшает результат, а не помогает)."""
    budget = client.input_char_budget
    if len(page_text) > budget:
        page_text = page_text[:budget]  # текст уже был показан модели по кускам строгой проверкой - здесь только повторная попытка на разумной части
    answer = timed_chat(
        client,
        system=BEST_EFFORT_SYSTEM,
        user=BEST_EFFORT_PROMPT_TMPL.format(topic=topic, page_text=page_text),
        max_tokens=500,
        disable_reasoning=True,
        max_continuations=1,
    )
    if answer.strip().upper().startswith("ЛУЧШИЙ ДОСТУПНЫЙ ОТВЕТ"):
        if not answer_numbers_grounded_in_source(answer, page_text):
            log("Мягкий ответ содержит цифры, которых нет в тексте - "
                "похоже на выдумку, не принимаю.")
            return None
        return answer
    return None


def try_full_page_text(client: LLMClient, html: str, topic: str) -> str:
    """Дополнительный "гейт" перед vision-fallback: проверяет ВЕСЬ
    основной текст страницы на достаточность ответа, а не только 5
    узких кандидатов из find_bonus_blocks.

    Бюджет одного запроса берётся из client.input_char_budget (учитывает
    num_ctx для Ollama или context_budget_tokens для remote-провайдеров)
    - если текст статьи не влезает целиком, режется на куски и
    прогоняется НЕСКОЛЬКИМИ последовательными заходами в LLM (до
    MAX_TEXT_CHUNKS), а не тупо обрезается с потерей содержимого.
    Останавливается на первом куске, где найден содержательный ответ
    С ЦИФРАМИ, РЕАЛЬНО ВЗЯТЫМИ ИЗ ТЕКСТА (см. answer_numbers_grounded_in_source)."""
    page_text = extract_main_page_text(html)
    if len(page_text) < 50:
        return None  # текста почти нет - vision точно понадобится

    budget = client.input_char_budget
    chunks = split_text_into_chunks(page_text, budget)
    if len(chunks) > 1:
        log(f"Основной текст страницы ({len(page_text)} симв.) не влезает "
            f"в один запрос (бюджет ~{budget} симв.) - разбиваю на "
            f"{min(len(chunks), MAX_TEXT_CHUNKS)} частей и проверяю "
            f"несколькими заходами в LLM.")

    for idx, chunk in enumerate(chunks[:MAX_TEXT_CHUNKS], start=1):
        if len(chunks) > 1:
            log(f"Проверяю часть {idx}/{min(len(chunks), MAX_TEXT_CHUNKS)} "
                f"основного текста страницы...")
        answer = timed_chat(
            client,
            system=FULL_TEXT_CHECK_SYSTEM,
            user=FULL_TEXT_CHECK_PROMPT_TMPL.format(topic=topic, page_text=chunk),
            max_tokens=500,
            disable_reasoning=True,
            max_continuations=1,  # см. пояснение в try_best_effort_answer - у этой модели больше 1 докрутки только вредит
        )
        if answer.strip().upper().startswith("СОДЕРЖАТЕЛЬНЫЙ БЛОК"):
            if not answer_numbers_grounded_in_source(answer, chunk):
                log(f"Ответ из части {idx} содержит цифры, которых нет "
                    f"буквально в тексте страницы - похоже на выдумку "
                    f"(экстраполяцию), не принимаю как достаточный.")
                continue
            return answer

    # Строгая проверка не нашла ТОЧНОГО ответа ни в одном куске - но
    # прежде чем идти в дорогой vision-fallback (который распознает
    # ТОТ ЖЕ ТЕКСТ с картинки, только медленнее и с OCR-артефактами),
    # пробуем мягкий гейт: может, в тексте есть релевантные цифры, но
    # не в точной запрошенной разбивке (см. BEST_EFFORT_SYSTEM).
    log("Строгая проверка не нашла точного ответа ни в одном куске. "
        "Пробую мягкий гейт - лучший доступный ответ с оговоркой об "
        "ограничениях данных, прежде чем переходить к vision...")
    best_effort = try_best_effort_answer(client, page_text, topic)
    if best_effort:
        log("Мягкий гейт дал лучший доступный ответ.")
        return best_effort

    return None


def find_bonus_blocks(html: str, base_url: str, keywords: list):
    """Ищет в HTML фрагменты текста, содержащие ключевые слова ЗАДАННОЙ
    ТЕМЫ (не только бонусы - keywords передаются извне, полученные из
    произвольного запроса пользователя), вместе с ближайшей ссылкой
    (href), если она есть внутри того же родительского элемента.

    Отфильтровывает навигационные "простыни" (меню сайта с десятками
    ссылок через ;), потому что оттуда попадала случайная первая
    ссылка (например на главную), а не осмысленный контентный блок.
    Кандидаты ранжируются по плотности ключевых слов - чем выше доля
    релевантной лексики в тексте, тем более содержательным считается
    блок (сплошное меню содержит 1 совпадение на сотни слов).
    """
    soup = BeautifulSoup(html, "html.parser")
    kw_pattern = re.compile("|".join(re.escape(k) for k in keywords), re.IGNORECASE)
    blocks = []

    for tag in soup.find_all(text=kw_pattern):
        parent = tag.parent
        context_el = parent
        for _ in range(2):
            if context_el.parent:
                context_el = context_el.parent

        text = context_el.get_text(separator=" ", strip=True)
        if len(text) < 15:
            continue  # слишком коротко, не несёт смысла

        # Признак навигационного меню: много ссылок И длинный список
        # пунктов через "; " - реальный контентный блок так не выглядит.
        num_links = len(context_el.find_all("a", href=True))
        semicolon_items = text.count(";")
        if num_links > 15 or semicolon_items > 15:
            continue  # похоже на меню сайта, а не на контент - пропускаем

        # Плотность ключевых слов: количество совпадений на 100 символов.
        # Чем выше - тем вероятнее, что это реально блок про бонусы,
        # а не случайное упоминание слова в длинном постороннем тексте.
        matches = len(kw_pattern.findall(text))
        density = matches / max(len(text), 1) * 100

        link = context_el.find("a", href=True)
        href = link["href"] if link else None
        link_text = link.get_text(strip=True) if link else None
        if href and href.startswith("/"):
            from urllib.parse import urljoin
            href = urljoin(base_url, href)

        blocks.append({"text": text[:1500], "href": href,
                       "link_text": link_text, "density": density})

    # Убираем дубликаты по тексту
    seen = set()
    unique_blocks = []
    for b in blocks:
        if b["text"] not in seen:
            seen.add(b["text"])
            unique_blocks.append(b)

    # Сортируем по убыванию плотности ключевых слов - самый вероятный
    # содержательный блок проверяем в LLM первым, а не первый попавшийся
    # в порядке появления в HTML.
    unique_blocks.sort(key=lambda b: b["density"], reverse=True)

    return unique_blocks[:5]  # не больше 5 кандидатов


def capture_scroll_screenshots(page) -> list:
    """Пошаговый скролл страницы с серией скриншотов (логика из
    step4_save_and_scroll.py). Возвращает список (путь, scroll_position)
    в порядке сверху вниз - позиция скролла нужна, чтобы потом можно
    было ТОЧНО вернуться на неё перед кликом по найденному элементу
    (после цикла страница остаётся на позиции ПОСЛЕДНЕГО скриншота,
    а элемент мог быть найден на любом из промежуточных).

    Очистка старых скриншотов теперь происходит в main() СРАЗУ при
    старте скрипта (а не здесь) - раньше, если в конкретном прогоне
    fallback на vision вообще не понадобился, PNG от ПРЕДЫДУЩЕГО
    прогона так и оставались в папке screens/, создавая путаницу
    (не ясно, откуда взялся тот или иной файл)."""
    os.makedirs(SCREENS_DIR, exist_ok=True)

    shots = []  # список (path, scroll_position)

    page.evaluate("window.scrollTo(0, 0)")
    time.sleep(0.5)
    shot_num = 1
    path = os.path.join(SCREENS_DIR, f"screen_{shot_num:02d}.png")
    page.screenshot(path=path)
    shots.append((path, 0))
    log(f"Скриншот {shot_num} сохранён: {path} (позиция скролла: 0)")

    viewport_height = page.viewport_size["height"]
    # БАГ (был): last_scroll_position стартовал с -1, а первый скриншот
    # уже находится на позиции 0. Если из-за медленной подгрузки SPA
    # первый page.mouse.wheel() ещё не успевал сдвинуть скролл (0 != -1),
    # условие остановки не срабатывало, и создавался ДУБЛИКАТ скриншота
    # на той же позиции 0 - лишний, зря потраченный vision-запрос.
    # Теперь стартуем с реальной позиции первого скриншота (0) и, если
    # после скролла позиция не изменилась, сначала ПОВТОРЯЕМ попытку
    # (страница могла ещё не дорисоваться), и только если несколько
    # попыток подряд не дали сдвига - считаем это концом страницы.
    last_scroll_position = 0
    stall_retries = 0
    MAX_STALL_RETRIES = 3

    while True:
        page.mouse.wheel(0, viewport_height)
        time.sleep(1)  # даём время догрузить контент/картинки по скроллу

        current_scroll_position = page.evaluate("window.scrollY")
        if current_scroll_position == last_scroll_position:
            stall_retries += 1
            if stall_retries >= MAX_STALL_RETRIES:
                log("Достигнут конец страницы, скролл остановлен.")
                break
            log(f"Скролл не сдвинулся (попытка {stall_retries}/{MAX_STALL_RETRIES}), "
                f"жду ещё - возможно, страница ещё дорисовывается...")
            time.sleep(1)
            continue
        stall_retries = 0
        last_scroll_position = current_scroll_position

        shot_num += 1
        path = os.path.join(SCREENS_DIR, f"screen_{shot_num:02d}.png")
        page.screenshot(path=path)
        shots.append((path, current_scroll_position))
        log(f"Скриншот {shot_num} сохранён: {path} (позиция скролла: {current_scroll_position})")

        if shot_num >= MAX_SCREENSHOTS:
            log(f"Достигнут лимит в {MAX_SCREENSHOTS} скриншотов, остановка.")
            break

    return shots


def try_expand_element(page, element_text: str, scroll_position: int = None) -> bool:
    """Пытается найти на реальной странице элемент с указанным текстом
    и кликнуть по нему (раскрыть выпадающий список/аккордеон).

    scroll_position: если передан - страница СНАЧАЛА возвращается на
    самый верх, а затем прокручивается ровно до этой позиции. Это
    важно, потому что после общего цикла скроллинга страница остаётся
    на позиции ПОСЛЕДНЕГО скриншота, а элемент был найден vision-
    моделью на одном из ПРОМЕЖУТОЧНЫХ скриншотов - без возврата к
    нужной позиции клик может попасть не туда или элемент будет
    перекрыт другой частью макета (sticky-шапка/сайдбар), которая
    на данной странице выглядит иначе, чем на позиции скриншота.

    Возвращает True, если клик удался."""
    if scroll_position is not None:
        page.evaluate("window.scrollTo(0, 0)")
        time.sleep(0.3)
        page.evaluate(f"window.scrollTo(0, {scroll_position})")
        time.sleep(0.5)

    try:
        # get_by_text ищет ЛЮБОЙ элемент с таким текстом (кнопка, div,
        # span и т.п.) - используем частичное совпадение (exact=False),
        # т.к. текст от vision-модели может немного отличаться от
        # реальной разметки (регистр, лишние пробелы).
        locator = page.get_by_text(element_text, exact=False).first
        locator.wait_for(state="visible", timeout=5000)
        locator.scroll_into_view_if_needed()
        try:
            locator.click(timeout=5000)
        except Exception as e_click:
            # Реальный случай: клик перехватывается другим элементом
            # макета (sticky-сайдбар "role=complementary" лежит поверх
            # нужного заголовка). force=True кликает по координатам
            # элемента напрямую, игнорируя перехват - подходит, когда
            # элемент реально виден на экране, просто загорожен для
            # обычной проверки "actionability" Playwright.
            log(f"Обычный клик по \"{element_text}\" не прошёл ({e_click}). "
                f"Пробую force click...")
            locator.click(timeout=5000, force=True)
        return True
    except Exception as e:
        log(f"Не удалось кликнуть по элементу \"{element_text}\": {e}")
        return False


def classify_link(client: LLMClient, link_text: str, topic: str) -> bool:
    """Минимальный запрос: отдаём модели ТОЛЬКО название ссылки (не
    весь блок текста), просим ответить одним словом VALID/INVALID -
    релевантна ли ссылка теме поиска. Гораздо дешевле по токенам и
    быстрее, чем анализ целого фрагмента текста."""
    answer = timed_chat(
        client,
        system=LINK_CLASSIFY_SYSTEM,
        user=LINK_CLASSIFY_PROMPT_TMPL.format(
            topic=topic, link_text=link_text),
        max_tokens=30,  # ответ короткий, но с запасом для reasoning-моделей
        disable_reasoning=True,
        max_continuations=0,  # см. пояснение в classify_url - докрутка не помогает этому паттерну
    )
    return "VALID" in answer.strip().upper() and "INVALID" not in answer.strip().upper()


