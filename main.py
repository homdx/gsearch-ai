def extract_keywords_from_query(query: str) -> list:
    """Универсальный способ получить ключевые слова темы ИЗ ЛЮБОГО
    произвольного запроса пользователя (не только про бонусы) - для
    оценки плотности релевантной лексики в найденных блоках HTML.
    Берём слова длиннее 3 символов, отбрасываем стоп-слова, приводим
    к нижнему регистру. Это грубый, но универсальный подход: не
    требует NLP-библиотек, работает для любой темы на русском.

    Слова длиннее 5 букв обрезаются до первых 5 (грубый псевдо-стемминг
    в духе "усечение основы"): "бонусов" -> "бонус", что как ПРЕФИКС
    (подстрока в начале слова) совпадёт и с "бонус", "бонусные",
    "бонусная", "бонусный" и т.п. Без обрезки искалось бы только
    буквальное "бонусов", теряя остальные падежи/формы того же корня."""
    words = re.findall(r"[а-яА-ЯёЁa-zA-Z0-9]{4,}", query.lower())
    keywords = [w[:5] for w in words if w not in STOPWORDS]
    return keywords or [query.lower()[:5]]  # если ничего не осталось - весь запрос как есть


def load_query(query_file: str) -> str:
    """Читает тему/запрос из текстового файла при старте (вместо
    зашитого в коде значения) - это и делает пайплайн универсальным:
    один и тот же main.py ищет что угодно, файл просто переписывается
    под новую задачу ("характеристики телефона X", "рецепт борща",
    "правила бонусов Аэрофлот" и т.п.)."""
    if not os.path.exists(query_file):
        raise FileNotFoundError(
            f"Файл с запросом не найден: {query_file}\n"
            f"Создай текстовый файл с темой поиска, например:\n"
            f'  echo "правила использования бонусов Аэрофлот" > {query_file}')
    with open(query_file, "r", encoding="utf-8") as f:
        query = f.read().strip()
    if not query:
        raise ValueError(f"Файл с запросом пуст: {query_file}")
    return query


