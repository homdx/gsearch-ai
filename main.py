def run_pipeline(page, client: LLMClient, url: str, topic: str, keywords: list,
                 already_loaded: bool = False):
    """Основной цикл: открыть страницу -> найти блоки -> спросить LLM ->
    если ссылка - перейти и повторить. Возвращает финальный текстовый
    ответ модели (для последующей валидации) или None, если текстовый
    путь не дал результата (тогда нужен fallback на vision).

    topic - тема поиска (из query.txt), keywords - ключевые слова для
    поиска релевантных блоков в HTML, оба универсальны для любой темы,
    не только бонусов.

    already_loaded=True - страница url УЖЕ открыта в page (например,
    её только что успешно загрузили и проверили на капчу в цикле
    выбора результата поиска) - первый переход пропускается, чтобы не
    навигировать на тот же самый URL ДВАЖДЫ подряд. Реальный случай:
    accuweather.com был медленным (несколько попыток по 20 сек), успешно
    открылся в цикле выбора кандидата, а затем run_pipeline тут же
    заново вызывал goto на тот же адрес - выглядело как зависание/цикл,
    хотя на самом деле страница просто открывалась второй раз впустую."""

    current_url = url
    visited_urls = set()
    for hop in range(MAX_HOPS):
        if current_url in visited_urls:
            # Ссылка ведёт сама на себя или на уже открытую страницу
            # (реальный случай: "Как потратить мили" на spend_miles
            # ведёт на spend_miles же) - лишний переход только тратит
            # время впустую, сразу переходим к fallback на vision.
            log(f"URL {current_url} уже был открыт в этом прогоне, "
                f"повторный переход не имеет смысла. Останавливаю цикл переходов.")
            return None, current_url
        visited_urls.add(current_url)

        if hop == 0 and already_loaded:
            log(f"[Переход {hop + 1}] Страница {current_url} уже загружена "
                f"ранее, повторная навигация не нужна.")
        else:
            log(f"[Переход {hop + 1}] Открываю: {current_url}")
            goto_with_retry(page, current_url)
            # Аэрофлот (и многие сайты с аналитикой/чатами) никогда не
            # "затихают" полностью - networkidle может не наступить вовсе.
            # Ждём domcontentloaded (гарантированно наступает) и пробуем
            # networkidle отдельно с более коротким таймаутом, но не падаем,
            # если он не пришёл - HTML к этому моменту обычно уже готов.
            page.wait_for_load_state("domcontentloaded", timeout=20000)
            try:
                page.wait_for_load_state("networkidle", timeout=8000)
            except Exception:
                silent_aware_print("networkidle не наступил за 8 сек (фоновая активность "
                      "сайта) - продолжаю с тем, что уже загружено.")
        # Доп. пауза: SPA-сайты (React/Vue) часто дорисовывают контент
        # ПОСЛЕ domcontentloaded/networkidle через JS - без этой паузы
        # find_bonus_blocks мог не найти ничего в ещё пустом DOM.
        time.sleep(1.5)

        html = page.content()
        blocks = find_bonus_blocks(html, current_url, keywords)

        if not blocks:
            # Одна повторная попытка после доп. ожидания - реальный
            # случай: страница была открыта слишком быстро для проверки,
            # и на первой попытке DOM ещё не успел дорисоваться.
            log("Блоков не найдено с первой попытки, жду ещё 3 сек и "
                "пробую снова (возможно, страница ещё дорисовывалась)...")
            time.sleep(3)
            html = page.content()
            blocks = find_bonus_blocks(html, current_url, keywords)

        if not blocks:
            log("Блоков с ключевыми словами по теме не найдено на этой странице.")
            return None, current_url

        log(f"Найдено {len(blocks)} кандидатов-фрагментов:")
        for i, b in enumerate(blocks, start=1):
            preview = b["text"][:100].replace("\n", " ")
            log(f"  [{i}] плотность={b['density']:.2f}  href={b['href']}  текст: {preview}...")

        # Пробуем кандидатов по очереди (от самого плотного по ключевым
        # словам), пока не найдём содержательный блок или не закончатся
        # варианты - раньше при первой неудаче (ссылка без href) весь
        # проход останавливался, хотя ниже могли быть рабочие варианты.
        for i, block in enumerate(blocks, start=1):
            try:
                # Если есть ссылка И текст самой ссылки - сначала пробуем
                # МИНИМАЛЬНЫЙ запрос: даём модели только название ссылки
                # (не весь фрагмент текста), просим одно слово VALID/INVALID.
                # Это в разы дешевле и быстрее, чем анализ целого блока.
                if block["href"] and block["link_text"]:
                    if block["href"] == current_url:
                        log(f"Кандидат [{i}]: ссылка ведёт на текущую же "
                            f"страницу, пропускаю без запроса к LLM.")
                        continue
                    log(f"Кандидат [{i}]: проверяю URL \"{block['href']}\" на соответствие теме...")
                    url_ok = classify_url(client, block["href"], topic)
                    if not url_ok:
                        # Пример реального случая (тема была про погоду в
                        # конкретном городе): переход на голый корень домена
                        # потерял город из URL, и сайт показал погоду по
                        # IP-геолокации вместо запрошенного города. Но
                        # проверка универсальна для ЛЮБОЙ темы - модель
                        # сравнивает URL с темой целиком (город, модель
                        # телефона, объект - что угодно), не только города.
                        log(f"Кандидат [{i}]: URL \"{block['href']}\" не соответствует теме "
                            f"(другой объект в URL или потеря контекста). Пропускаю.")
                        continue
                    log(f"Кандидат [{i}]: проверяю ссылку по названию "
                        f"\"{block['link_text']}\"...")
                    is_valid = classify_link(client, block["link_text"], topic)
                    log(f"Кандидат [{i}]: вердикт по ссылке = "
                        f"{'VALID' if is_valid else 'INVALID'}")

                    if is_valid:
                        log(f"Ссылка [{i}] релевантна. Перехожу: {block['href']}")
                        current_url = block["href"]
                        break
                    else:
                        log(f"Ссылка [{i}] нерелевантна теме. Пробую следующего кандидата.")
                        continue

                # Ссылки нет (или не удалось вытащить текст ссылки) -
                # тогда смотрим на содержимое блока целиком, как раньше.
                log(f"Кандидат [{i}]: ссылки нет, анализирую текст блока целиком...")
                answer = analyze_text_block(client, block["text"], topic)
                silent_aware_print("Ответ LLM по текстовому фрагменту:")
                silent_aware_print(answer)

                if answer.strip().upper().startswith("ЭТО ССЫЛКА"):
                    if block["href"]:
                        log(f"Кандидат [{i}]: проверяю URL \"{block['href']}\" на соответствие теме...")
                        if not classify_url(client, block["href"], topic):
                            log(f"Кандидат [{i}] - ссылка на {block['href']}, но URL не "
                                f"соответствует теме (другой объект в URL). Пропускаю.")
                            continue
                        log(f"Модель определила фрагмент [{i}] как ссылку. Перехожу: {block['href']}")
                        current_url = block["href"]
                        break
                    else:
                        log(f"Кандидат [{i}] - ссылка, но href не найден. Пробую следующего кандидата.")
                        continue
                else:
                    # БАГ (был): блок принимался как финальный ответ
                    # СРАЗУ, без проверки, отвечает ли он на вопрос по
                    # существу. Реальный случай: тема "погода в Казани
                    # 8 августа", а блок содержал только ТЕКУЩУЮ
                    # температуру (виджет "сейчас 20°") без привязки к
                    # запрошенной дате - валидатор в конце справедливо
                    # назвал это галлюцинацией/нерелевантным ответом.
                    # Теперь дополнительно проверяем достаточность
                    # ответа ПЕРЕД тем, как его принять - если блок
                    # слишком общий, пробуем следующего кандидата
                    # вместо немедленного возврата первого попавшегося.
                    is_sufficient, _, _ = analyze_vision_answer(client, answer, topic)
                    if is_sufficient:
                        return answer, current_url
                    else:
                        log(f"Кандидат [{i}]: блок содержательный, но НЕ "
                            f"даёт конкретного ответа по существу темы "
                            f"(слишком общий/не по датe/etc). Пробую "
                            f"следующего кандидата.")
                        continue
            except RuntimeError as e:
                # Сбой конкретного LLM-запроса (например бесплатная
                # модель временно недоступна/лимит исчерпан - реальный
                # случай: OpenRouter вернул {"error": ...} вместо
                # ответа, что раньше роняло весь скрипт с невнятным
                # KeyError). Пропускаем ЭТОГО кандидата, пробуем
                # следующего - не теряем весь прогон из-за одного сбоя.
                log(f"Кандидат [{i}]: ошибка LLM-запроса ({e}). "
                    f"Пробую следующего кандидата.")
                continue
        else:
            # Ни один из узких кандидатов не подошёл - но это не
            # значит, что ответа нет на странице вообще: кандидаты
            # ищутся по плотности ключевых слов в коротких блоках, а
            # реальный текст статьи может быть в обычном параграфе,
            # не попавшем в эту узкую выборку (реальный случай: все
            # 5 кандидатов оказались навигацией/рекламой, а число
            # "50 рейсов" было прямо в заголовке статьи на той же
            # странице). Дополнительный "гейт" перед дорогим
            # vision-fallback - проверяем ВЕСЬ основной текст страницы
            # ОДНИМ запросом.
            log("Ни один узкий кандидат не подошёл. Пробую доп. проверку "
                "по всему основному тексту страницы перед переходом к vision...")
            full_text_answer = try_full_page_text(client, html, topic)
            if full_text_answer:
                log("Полный текст страницы дал содержательный ответ.")
                return full_text_answer, current_url
            log("И полный текст страницы не дал ответа.")
            return None, current_url

    silent_aware_print(f"Достигнут лимит переходов ({MAX_HOPS}), содержательный блок не найден.")
    return None, current_url


