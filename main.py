def log(msg: str):
    """Печать с таймштампом [ЧЧ:ММ:СС], чтобы было видно, что скрипт
    жив и на каком шаге сейчас идёт (особенно важно для долгих
    локальных LLM-запросов, которые могут идти минуты).
    В silent-режиме (RUN_STATS['silent'] == True) ничего не печатает -
    единственный вывод в консоль тогда - финальный JSON в конце."""
    if RUN_STATS["silent"]:
        return
    print(f"[{time.strftime('%H:%M:%S')}] {msg}")


def silent_aware_print(*args, **kwargs):
    """Замена обычному print() для мест, где раньше был голый print(...)
    без таймштампа - тоже должна молчать в silent-режиме."""
    if RUN_STATS["silent"]:
        return
    print(*args, **kwargs)


