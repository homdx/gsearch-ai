def generate_search_query(client: LLMClient, topic: str) -> str:
    """Мини-запрос к LLM: вместо того чтобы отправлять в Google сырой
    текст темы из query.txt как есть (который может содержать разговорные
    слова вроде "найди", "подскажи" и т.п.), просим модель САМУ
    сформулировать оптимальный поисковый запрос. Ничего не хардкодится -
    формулировка запроса становится задачей модели, а не кода."""
    answer = timed_chat(
        client,
        system=SEARCH_QUERY_SYSTEM,
        user=SEARCH_QUERY_PROMPT_TMPL.format(topic=topic),
        max_tokens=40,
    )
    # Модель иногда всё равно оборачивает ответ в кавычки - подчищаем.
    # Берём только ПЕРВУЮ строку - реальный случай: модель вместо
    # запроса начала рассуждать ("The user wants a search query for...")
    # и была обрублена по max_tokens посреди фразы. Многострочный или
    # длинный "рассуждающий" ответ - явный признак, что инструкция
    # "одна строка, только запрос" была проигнорирована.
    first_line = answer.strip().splitlines()[0] if answer.strip() else ""
    query = first_line.strip().strip('"').strip("«»").strip()

    looks_like_reasoning = (
        len(answer.strip().splitlines()) > 1  # многострочный ответ
        or len(query.split()) > 12            # поисковый запрос редко длиннее ~12 слов
        or len(query) > 120
    )

    if not query or looks_like_reasoning:
        log(f"LLM вернула не похожее на поисковый запрос ({answer[:80]!r}...), "
            f"использую тему как есть.")
        return topic
    return query


