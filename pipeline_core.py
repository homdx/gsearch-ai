def make_give_up_summary(client: LLMClient, topic: str, raw_notes: str, sites_count: int) -> str:
    """Сжимает неудачный результат прогона в короткое честное резюме
    вместо того, чтобы отдавать пользователю (и валидатору) сырую
    простыню из нескольких длинных vision-описаний подряд. Реальный
    случай: прогон длиной больше часа, проверивший 3 сайта, вернул
    final_answer из 5 склеенных verbose-описаний скриншотов - валидатору
    пришлось писать огромное эссе, чтобы разобраться, хотя по существу
    ответ был "точных данных на конкретную дату не нашлось, но сайт
    в целом про погоду в Казани".

    БАГ (был): если raw_notes не влезал в бюджет, просто ОБРЕЗАЛСЯ
    (raw_notes[:budget]) - могло отрезать самое важное (например
    единственную полезную деталь в конце текста). Теперь - настоящий
    двухпроходный map-reduce, как в try_full_page_text/
    synthesize_from_vision_answers: сначала режем на куски по бюджету
    и сжимаем КАЖДЫЙ кусок отдельно (map), затем объединяем все
    промежуточные выжимки (они уже короткие, гарантированно влезут в
    любой бюджет) и делаем ФИНАЛЬНЫЙ проход сжатия до 2-4 предложений
    (reduce) - портянка укорачивается на каждом шаге, а не обрезается
    вслепую."""
    budget = client.input_char_budget

    if len(raw_notes) <= budget:
        # Влезает целиком - один проход, как раньше.
        return timed_chat(
            client,
            system=GIVE_UP_SUMMARY_SYSTEM,
            user=GIVE_UP_SUMMARY_PROMPT_TMPL.format(
                topic=topic, sites_count=sites_count, raw_notes=raw_notes),
            max_tokens=300,
        )

    # MAP: режем на куски по бюджету, сжимаем каждый по отдельности.
    chunks = split_text_into_chunks(raw_notes, budget)
    chunks = chunks[:MAX_TEXT_CHUNKS]  # тот же предохранитель от бесконечного числа заходов
    log(f"Заметки для резюме ({len(raw_notes)} симв.) не влезают в один "
        f"запрос (бюджет ~{budget} симв.) - сжимаю в {len(chunks)} проходов, "
        f"затем объединяю в финальное резюме.")

    partial_summaries = []
    for idx, chunk in enumerate(chunks, start=1):
        partial = timed_chat(
            client,
            system=PARTIAL_SUMMARY_SYSTEM,
            user=PARTIAL_SUMMARY_PROMPT_TMPL.format(
                topic=topic, idx=idx, total=len(chunks), chunk=chunk),
            max_tokens=150,
        )
        partial_summaries.append(f"[Часть {idx}] {partial}")

    # REDUCE: объединяем промежуточные выжимки (они короткие - до
    # len(chunks)*150 токенов суммарно, что в разы меньше исходного
    # raw_notes и гарантированно влезает в бюджет любого разумного
    # размера) в ОДНО финальное короткое резюме.
    combined_partials = "\n".join(partial_summaries)
    return timed_chat(
        client,
        system=GIVE_UP_SUMMARY_SYSTEM,
        user=GIVE_UP_SUMMARY_PROMPT_TMPL.format(
            topic=topic, sites_count=sites_count, raw_notes=combined_partials),
        max_tokens=300,
    )


