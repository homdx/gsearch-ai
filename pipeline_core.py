def summarize_validator_verdict(client: LLMClient, topic: str, validator_answer: str) -> str:
    """Отдельный дополнительный LLM-запрос, который сжимает заключение
    валидатора (validator_answer) до короткой формы перед показом
    пользователю - вместо длинного нумерованного обоснования на
    несколько абзацев.

    ВАЖНО: вызывается уже ПОСЛЕ того, как success (True/False) в
    main.py определён по ИСХОДНОМУ, несжатому validator_answer -
    сжатие никак не может повлиять на этот исход, даже если
    перефразирует строку ВЕРДИКТ не точь-в-точь. Сама проверка на
    "галлюцинацию" всегда остаётся на несжатом тексте.

    Если сам запрос на сжатие упадёт (сеть, пустой ответ и т.п.) - не
    роняем из-за этого весь прогон, просто отдаём исходный, несжатый
    validator_answer как есть (лучше длинный вердикт, чем никакого).

    ПРОВЕРКА РЕЗУЛЬТАТА: модель, которая должна сокращать текст, иногда
    вместо этого его РАСШИРЯЕТ (глюк/пересказ вместо сжатия, повторение
    формулировок другими словами, дописывание "воды") - типичный
    признак, что запрос не выполнил свою задачу. Если "сжатый" ответ
    оказался НЕ короче исходного (длина в символах >= длины
    validator_answer) - это явный сигнал, что сжатия не произошло,
    поэтому такой результат отбрасываем и возвращаем исходный
    validator_answer, а не раздутый "суррогат"."""
    if not validator_answer or not validator_answer.strip():
        return validator_answer
    try:
        summary = timed_chat(
            client,
            system=VALIDATOR_SUMMARY_SYSTEM,
            user=VALIDATOR_SUMMARY_PROMPT_TMPL.format(
                topic=topic, validator_answer=validator_answer),
            max_tokens=200,
        )
    except Exception as e:
        log(f"Не удалось сжать заключение валидатора ({e}) - "
            f"отдаю исходный несжатый текст.")
        return validator_answer

    summary = summary.strip() if summary else ""
    if not summary:
        log("Сжатие вердикта вернуло пустой ответ - отдаю исходный несжатый текст.")
        return validator_answer

    if len(summary) >= len(validator_answer):
        # Сжатие не удалось (модель расширила текст вместо того, чтобы
        # сократить) - не отдаём пользователю "сжатый", но на деле более
        # длинный текст, возвращаем оригинал.
        log(f"Сжатый вердикт ({len(summary)} симв.) оказался не короче "
            f"исходного ({len(validator_answer)} симв.) - похоже, модель "
            f"не сократила текст, а переписала/расширила его. Отдаю "
            f"исходный несжатый текст.")
        return validator_answer

    return summary


