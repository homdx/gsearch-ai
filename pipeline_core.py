def group_vision_answers_by_budget(vision_answers: list, budget: int) -> list:
    """Группирует ЦЕЛЫЕ описания скриншотов в пачки, укладывающиеся в
    бюджет символов - в отличие от split_text_into_chunks (посимвольная
    резка для try_full_page_text), здесь режем по границам ОТДЕЛЬНЫХ
    описаний, а не посередине текста - иначе можно разорвать конкретное
    описание скриншота (со всеми его цифрами) прямо на середине фразы,
    и синтез увидит только половину нужных данных."""
    groups = []
    current_group = []
    current_len = 0
    for answer in vision_answers:
        answer_len = len(answer) + 2  # +2 на "\n\n"-разделитель
        if current_group and current_len + answer_len > budget:
            groups.append(current_group)
            current_group = []
            current_len = 0
        current_group.append(answer)
        current_len += answer_len
    if current_group:
        groups.append(current_group)
    return groups


def synthesize_from_vision_answers(client: LLMClient, vision_answers: list, topic: str) -> str:
    """Финальный синтез ПОСЛЕ того, как все скриншоты обработаны по
    отдельности. Реальный случай: 4 скриншота подряд (таблица с
    данными о сгоревших складах) были каждый по отдельности отмечены
    как "не относится к теме", потому что название компании было
    упомянуто в ДРУГОМ скриншоте той же страницы, а не в каждом кадре
    таблицы - хотя даты/локации/итоговая статистика совпадали. Вместо
    того чтобы доверять покриншотной самооценке "достаточно/
    недостаточно", даём модели ВСЕ описания сразу - контекст, видимый
    только при чтении их вместе, помогает собрать правильный итог
    (например "19 пострадавших объектов" из последнего скриншота).

    БАГ (был): все описания склеивались в ОДИН промпт без проверки
    бюджета контекста - при большом числе скриншотов (особенно если
    max_scroll_screenshots в ини поднят выше дефолта) это могло
    превысить контекст модели. Теперь описания группируются в пачки
    по client.input_char_budget, и синтез пробуется на каждой пачке
    последовательно (несколько заходов в LLM), как и в
    try_full_page_text."""
    budget = client.input_char_budget
    groups = group_vision_answers_by_budget(vision_answers, budget)

    if len(groups) > 1:
        log(f"Все описания скриншотов вместе ({sum(len(a) for a in vision_answers)} "
            f"симв.) не влезают в один запрос (бюджет ~{budget} симв.) - "
            f"разбиваю на {len(groups)} пачек и синтезирую несколькими заходами.")

    for idx, group in enumerate(groups[:MAX_TEXT_CHUNKS], start=1):
        if len(groups) > 1:
            log(f"Синтезирую по пачке {idx}/{min(len(groups), MAX_TEXT_CHUNKS)}...")
        combined = "\n\n".join(group)
        answer = timed_chat(
            client,
            system=VISION_SYNTHESIS_SYSTEM,
            user=VISION_SYNTHESIS_PROMPT_TMPL.format(
                topic=topic, count=len(group), combined=combined),
            max_tokens=500,
            disable_reasoning=True,
            max_continuations=1,
        )
        if answer.strip().upper().startswith("СОДЕРЖАТЕЛЬНЫЙ БЛОК"):
            if not answer_numbers_grounded_in_source(answer, combined):
                log(f"Синтезированный ответ по пачке {idx} содержит цифры, "
                    f"которых нет в исходных описаниях - похоже на "
                    f"выдумку, пробую следующую пачку.")
                continue
            return answer

    # Строгий синтез не нашёл точного ответа - как и в try_full_page_text,
    # пробуем мягкий гейт: возможно, в описаниях скриншотов уже есть
    # релевантные цифры (пусть не в точной запрошенной разбивке), и
    # можно дать лучший доступный ответ с явной оговоркой, вместо
    # молчаливого отказа (см. BEST_EFFORT_SYSTEM - тот же гейт, что и
    # для обычного текста страницы, переиспользуем без изменений)."""
    log("Строгий синтез по скриншотам не дал точного ответа. Пробую "
        "мягкий гейт - лучший доступный ответ с оговоркой...")
    combined_all = "\n\n".join(vision_answers)
    best_effort = try_best_effort_answer(client, combined_all, topic)
    if best_effort:
        log("Мягкий гейт по скриншотам дал лучший доступный ответ.")
        return best_effort

    return None


def process_candidate_site(page, text_client: LLMClient, vision_client: LLMClient,
                           topic: str, keywords: list, start_url: str,
                           already_loaded: bool):
    """Полная обработка ОДНОГО сайта: текстовый путь (run_pipeline) ->
    если не хватило - vision-fallback по скриншотам. Возвращает
    (final_answer, is_sufficient) - is_sufficient нужен вызывающему
    коду, чтобы решить, пробовать ли СЛЕДУЮЩИЙ сайт из выдачи Google,
    или этого достаточно.

    БАГ (был): раньше это было прямо внутри main(), одним неразрывным
    блоком - если и текст, и ВСЕ скриншоты vision не давали ответа
    (реальный случай: accuweather.com не показал температуру на
    конкретную дату ни в календаре, ни в графике - 5 скриншотов,
    ~19 минут), результат всё равно уходил на финальную валидацию,
    хотя в выдаче Google был ВТОРОЙ кандидат (world-weather.ru с датой
    прямо в URL), который мог дать ответ быстрее и надёжнее - но
    пайплайн его даже не пробовал."""
    final_text_answer, _ = run_pipeline(
        page, text_client, start_url, topic, keywords, already_loaded=already_loaded)

    if final_text_answer is not None:
        # Текстовый путь сам уже прошёл проверку достаточности внутри
        # run_pipeline (см. analyze_vision_answer-проверку перед return) -
        # если он вернул ответ, считаем его достаточным.
        return final_text_answer, True

    log("Текстовый путь не дал результата. Скроллю страницу и "
        "делаю серию скриншотов для vision-модели...")
    screenshots = capture_scroll_screenshots(page)  # [(path, scroll_position), ...]
    vision_prompt = VISION_PROMPT_TMPL.format(topic=topic)

    vision_answers = []
    expansions_used = 0
    is_sufficient = False
    for i, (shot_path, scroll_position) in enumerate(screenshots, start=1):
        log(f"Обрабатываю скриншот {i}/{len(screenshots)}: {shot_path} "
            f"(позиция скролла: {scroll_position})")
        answer = timed_chat_vision(vision_client, vision_prompt, shot_path)
        silent_aware_print(answer)
        vision_answers.append(f"[Скриншот {i}]\n{answer}")

        is_sufficient, element_text, zoom_region = analyze_vision_answer(
            text_client, answer, topic)

        if expansions_used < MAX_EXPANSIONS_TOTAL and element_text:
            log(f"Найден потенциально полезный элемент: "
                f"\"{element_text}\". Возвращаюсь к позиции скролла "
                f"{scroll_position} и пробую раскрыть...")
            if try_expand_element(page, element_text, scroll_position):
                expansions_used += 1
                time.sleep(1)
                expanded_shot = os.path.join(
                    SCREENS_DIR, f"screen_{i:02d}_expanded.png")
                page.screenshot(path=expanded_shot)
                log(f"Скриншот после раскрытия сохранён: {expanded_shot}")
                expanded_answer = timed_chat_vision(
                    vision_client, vision_prompt, expanded_shot)
                silent_aware_print(expanded_answer)
                vision_answers.append(
                    f"[Скриншот {i} после раскрытия \"{element_text}\"]\n"
                    f"{expanded_answer}")
            else:
                log(f"Элемент \"{element_text}\" найден в описании, "
                    f"но кликнуть по нему на странице не удалось.")
        elif not is_sufficient and zoom_region:
            log(f"Модель указала, что детали мелкие и находятся "
                f"в зоне \"{zoom_region}\". Делаю увеличенный "
                f"скриншот этой области...")
            zoomed_shot = os.path.join(
                SCREENS_DIR, f"screen_{i:02d}_zoom_{zoom_region}.png")
            if capture_zoomed_region(page, zoom_region, zoomed_shot):
                zoomed_answer = timed_chat_vision(
                    vision_client, vision_prompt, zoomed_shot)
                silent_aware_print(zoomed_answer)
                vision_answers.append(
                    f"[Скриншот {i}, увеличенная зона \"{zoom_region}\"]\n"
                    f"{zoomed_answer}")
                is_sufficient, _, _ = analyze_vision_answer(
                    text_client, zoomed_answer, topic)

        if is_sufficient:
            log(f"Скриншот {i} уже содержит достаточный ответ по теме. "
                f"Останавливаю обработку остальных скриншотов.")
            break

    if not is_sufficient and len(vision_answers) > 1:
        # Ранняя остановка по отдельным скриншотам не сработала - не
        # сдаёмся сразу, пробуем СИНТЕЗ по всем описаниям вместе.
        # Реальный случай: 4 из 7 скриншотов таблицы были ошибочно
        # помечены как "не по теме" по отдельности (название бренда
        # было в другом скриншоте), но итоговая цифра ("19 объектов")
        # прямо присутствовала в тексте одного из них - синтез читает
        # все описания сразу и видит сквозной контекст.
        log("Ни один скриншот по отдельности не был отмечен как "
            "достаточный. Пробую синтез ответа по ВСЕМ описаниям сразу...")
        synthesized = synthesize_from_vision_answers(text_client, vision_answers, topic)
        if synthesized:
            log("Синтез по всем скриншотам дал содержательный ответ.")
            return synthesized, True

    final_answer = "\n\n".join(vision_answers)
    return final_answer, is_sufficient


def wait_for_serp_stable(page, timeout_sec: float = 4.0, poll_sec: float = 0.4) -> None:
    """Ждёт, пока содержимое выдачи (#search) перестанет меняться, прежде
    чем читать текст из DOM (шаг 1 в check_google_snippet_answer).

    БАГ (был): проверка DOM и скриншот для vision делались сразу, без
    единой паузы. AI Overview у Google - асинхронный блок: он часто
    дорисовывается с задержкой (свой скелетон-лоадер), и inner_text()
    "в лоб" ловил либо пустое место, либо недорисованный лоадер -
    текстовая проверка не находила "ОТВЕТ:", хотя ответ появлялся на
    экране секундой позже. Реальный случай: тема "Разделить 152/145" -
    и текст DOM, и последующий скриншот снимались в момент t=0, AI
    Overview дорисован к t≈1-2 сек, и vision по итогу тоже ловил пустой
    кадр (скриншот делался следом за неудачной текстовой проверкой, без
    новой паузы).

    БАГ (был, вторая версия фикса): пауза стояла перед screenshot(), а
    не перед первым чтением DOM - то есть после того как первая (пустая)
    попытка чтения DOM уже провалилась. Раз мы ждём стабилизации один
    раз, ждать нужно ДО первого обращения к #search (шаг 1), а не между
    шагом 1 и шагом 2 - иначе шаг 1 почти всегда мимо, и полезной работы
    от паузы никакой, вся нагрузка ложится на дорогой vision-fallback.
    После этой паузы скриншот на шаге 2 снимается сразу, без повторного
    ожидания - контент уже стабилен.

    Фикс: не фиксированный sleep (ненадёжно - иногда рендерится 3-5 сек,
    иногда почти мгновенно), а polling по хэшу текста #search - как
    только два последовательных снимка текста совпали, считаем рендер
    завершённым. Если за timeout_sec стабилизации не случилось - просто
    прекращаем ждать и идём дальше с тем, что есть (лучше, чем зависнуть
    навсегда, если что-то меняется постоянно, например реклама/анимация).

    БАГ (был, третья версия): "стабильность" засчитывалась уже на первой
    паре опросов, если оба вернули один и тот же ПУСТОЙ (или очень
    короткий) текст - это ложная стабильность: #search ещё не начал
    рендериться вообще, а не "перестал меняться". Реальный случай: лог
    показал вход в функцию и "стабилизировалось" в ту же секунду
    (17:34:05 -> 17:34:05), i.e. 0 полных poll-циклов - #search в этот
    момент был пуст, следующий скриншот поймал белый экран без AI
    Overview. Фикс: (1) обязательный минимум min_polls опросов ПОДРЯД с
    одинаковым хэшем, а не один; (2) пустой/слишком короткий текст
    (< min_text_len символов) вообще не считается кандидатом на
    стабильность - ждём, пока хоть что-то появится, независимо от
    хэш-сравнения.
    """
    import hashlib as _hashlib
    min_polls = 2       # минимум подряд одинаковых непустых снимков
    min_text_len = 50   # короче - считаем "ещё не отрендерилось"
    deadline = time.monotonic() + timeout_sec
    prev_hash = None
    stable_count = 0
    while time.monotonic() < deadline:
        try:
            text = page.locator("#search").first.inner_text(timeout=1000)
        except Exception:
            text = ""
        stripped = text.strip()
        if len(stripped) < min_text_len:
            # Контент ещё не появился вообще - не засчитываем как
            # "стабильно", просто ждём дальше.
            prev_hash = None
            stable_count = 0
            time.sleep(poll_sec)
            continue
        cur_hash = _hashlib.sha1(stripped.encode("utf-8", errors="ignore")).hexdigest()
        if cur_hash == prev_hash:
            stable_count += 1
            if stable_count >= min_polls:
                log(f"Выдача Google стабилизировалась ({stable_count} "
                    f"одинаковых снимков подряд, AI Overview дорисован), "
                    f"делаю скриншот.")
                return
        else:
            stable_count = 0
        prev_hash = cur_hash
        time.sleep(poll_sec)
    log(f"Выдача Google не стабилизировалась за {timeout_sec} сек - "
        f"делаю скриншот как есть (возможна постоянная анимация/реклама).")


def check_google_snippet_answer(page, vision_client, text_client, topic, cfg):
    """Перед тем как открывать любой сайт из выдачи, проверяем - вдруг ответ
    уже есть прямо на странице результатов Google (featured snippet под
    первым результатом, или блок AI Overview). Сначала пробуем ДЕШЁВЫЙ
    текстовый путь через DOM (inner_text), и только если он ничего не дал -
    падаем в vision по скриншоту, точно так же, как обычные сайты сперва
    проверяются текстом (run_pipeline), а vision - fallback на крайний
    случай.

    Реальный случай: тема "Август 2026 распродажа авиакомпании даты?" -
    ответ ("Nordwind, с 5 по 11 августа 2026") был виден прямо в тексте
    featured snippet на странице Google, а пайплайн вместо этого шёл на
    первый результат (капча), потом на второй (галлюцинация) - хотя текст
    ответа лежал в DOM с самого начала, бесплатно и без единого vision-
    запроса.

    Возвращает текст ответа, если он найден прямо в выдаче, иначе None (и
    вызывающий код идёт по обычному пути - открывает сайты по очереди).
    """
    if not cfg.getboolean("google", "check_snippet_before_opening_links", fallback=True):
        return None

    log("Смотрю, нет ли готового ответа прямо в выдаче Google (сниппет/AI "
        "Overview), прежде чем открывать сайты по очереди...")

    wait_for_serp_stable(
        page,
        timeout_sec=cfg.getfloat("google", "serp_stable_timeout_sec", fallback=4.0),
        poll_sec=cfg.getfloat("google", "serp_stable_poll_sec", fallback=0.4),
    )

    # --- Шаг 1: текст из DOM, без единого vision/скриншот-запроса ---
    search_text = ""
    try:
        search_text = page.locator("#search").first.inner_text(timeout=5000)
    except Exception as e:
        log(f"Не удалось прочитать текст выдачи из DOM ({e}), "
            f"перехожу сразу к vision-проверке скриншота.")

    # Верхняя часть выдачи (сниппет/AI Overview обычно в первых ~2000
    # символов) - не тащим в LLM весь список из 10 результатов с
    # URL-мусором, это только размывает ответ и тратит бюджет токенов.
    top_text = search_text.strip()[:2000]

    if top_text:
        text_answer = timed_chat(
            text_client,
            system=GOOGLE_SNIPPET_TEXT_SYSTEM,
            user=GOOGLE_SNIPPET_TEXT_PROMPT_TMPL.format(topic=topic, text=top_text),
            # БАГ (был): max_tokens=200, max_continuations=1 - модель тратит
            # бюджет на пересказ "The user is asking..." + перечисление
            # сниппетов ДО того, как дойти до "ОТВЕТ:", и сам ответ обрывался
            # на середине предложения ("...до 9 августа 2026 года вклю").
            # Бюджет побольше и лишняя докрутка дают модели место закончить
            # мысль после преамбулы, которую она всё равно пишет вопреки
            # системному промпту.
            #
            # БАГ (был, 2026-08-08): max_tokens=400, max_continuations=2 всё
            # равно оказалось мало для reasoning-моделей (например nemotron
            # через OpenRouter free-тир), которые ИГНОРИРУЮТ disable_reasoning
            # (payload "reasoning": {"exclude": true}) и всё равно тратят
            # ~300-350 токенов каждый раунд наChain-of-Thought прямо в поле
            # content (не в отдельном "reasoning"!). Реальный случай: 3
            # раунда по 400 токенов (1200 суммарно) - и ни разу не дошли до
            # "ОТВЕТ:", в full_content склеились три обрывка рассуждений,
            # которые валидатор потом справедливо забраковал как галлюцинацию.
            # Подняли бюджет и докрутки - это смягчение, а не гарантия: если
            # модель тратит на рассуждения БОЛЬШЕ нового бюджета, проблема
            # повторится и на большем бюджете, просто позже. Настоящее
            # решение - детектировать отсутствие "ОТВЕТ:" после докруток и
            # не отдавать сырую CoT-кашу как final_answer (TODO).
            max_tokens=800,
            disable_reasoning=True,
            max_continuations=3,
        )
        silent_aware_print(text_answer)
        stripped = text_answer.strip()
        # БАГ (был): проверяли stripped.upper().startswith("ОТВЕТ") - но
        # nemotron иногда игнорирует "отвечай СРАЗУ" и сначала пишет
        # рассуждения (по-английски), а "ОТВЕТ:" оказывается где-то в
        # середине текста. Реальный случай: модель честно перечислила все
        # найденные распродажи и в конце написала "ОТВЕТ: Nordwind Airlines
        # проводит распродажу с 5 по 11 августа 2026..." - но startswith
        # это пропустил, и пайплайн зря пошёл в vision-скриншот. Теперь
        # ищем "ОТВЕТ:" где угодно в тексте, а не только в первой строке.
        answer_marker = "ОТВЕТ:"
        marker_pos = stripped.upper().find(answer_marker)
        extracted = stripped[marker_pos + len(answer_marker):].strip() if marker_pos != -1 else ""
        # БАГ: модель нередко пишет рассуждения вроде "...точной информации
        # нет, поэтому ответ: NONE" - слово "ответ:" тут есть, но это НЕ
        # найденный ответ, а её же собственное объяснение отказа. Раньше
        # marker_pos != -1 срывался бы и возвращал текст "NONE" как будто
        # это готовый ответ, и цикл по сайтам пропускался с мусором вместо
        # final_answer. Проверяем, что за "ОТВЕТ:" не пустота и не само
        # слово NONE.
        if marker_pos != -1 and extracted and extracted.upper() != "NONE":
            log("Текст выдачи Google (DOM, без скриншота) уже содержит "
                "готовый ответ - сайты открывать не нужно.")
            return extracted
        log("В тексте DOM выдачи Google конкретного ответа не нашлось "
            "(AI Overview часто рисуется поверх обычного текста и не "
            "виден через inner_text). Пробую vision по скриншоту...")
    else:
        log("Текст выдачи Google через DOM пуст, пробую vision по скриншоту...")

    # --- Шаг 2: vision-fallback по скриншоту (AI Overview/виджеты, ---
    # --- которые не читаются простым inner_text) ---
    shot_path = os.path.join(SCREENS_DIR, "screen_serp_00.png")
    page.screenshot(path=shot_path)
    vision_prompt = VISION_PROMPT_TMPL.format(topic=topic)
    answer = timed_chat_vision(vision_client, vision_prompt, shot_path)
    silent_aware_print(answer)
    is_sufficient, element_text, _zoom_region = analyze_vision_answer(
        text_client, answer, topic)

    if (not is_sufficient and element_text
            and cfg.getboolean("google", "expand_ai_overview", fallback=True)):
        log(f"В выдаче найден потенциально полезный свёрнутый элемент "
            f"(например AI Overview \"Показать ещё\"): \"{element_text}\". "
            f"Пробую раскрыть...")
        if try_expand_element(page, element_text):
            time.sleep(1)
