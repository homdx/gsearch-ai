def analyze_vision_answer(client: LLMClient, vision_answer: str, topic: str):
    """Объединённая проверка ОДНИМ запросом вместо нескольких отдельных.
    Возвращает кортеж (is_sufficient, element_text, zoom_region).

    zoom_region - универсальный (не привязанный к конкретной теме)
    способ попросить модель указать ПРИМЕРНУЮ область экрана, где
    находятся мелкие детали (число в ячейке календаря, значение в
    таблице характеристик, строка в прайс-листе - что угодно), чтобы
    затем сделать увеличенный скриншот именно этой области и
    распознать её точнее.

    БАГ (был): max_tokens=80 без disable_reasoning - reasoning-модель
    (nemotron) тратила лимит на служебное поле, три строки ответа
    (SUFFICIENT/ELEMENT/ZOOM_REGION) обрывались, а докрутка (дефолтные
    max_continuations=2) заводила модель в цикл путаницы про "was my
    previous response cut off?" Реальный случай: явно содержательный
    ответ про дождь в Казани (упомянут в 3 из 4 периодов дня) был
    ошибочно отклонён как is_sufficient=False после 50+ секунд
    бесплодной докрутки, хотя по существу отвечал на вопрос."""
    answer = timed_chat(
        client,
        system=ANALYSIS_CHECK_SYSTEM,
        user=ANALYSIS_CHECK_PROMPT_TMPL.format(topic=topic, vision_answer=vision_answer),
        max_tokens=150,
        disable_reasoning=True,
        max_continuations=1,
    )
    is_sufficient = False
    element_text = None
    zoom_region = None
    for line in answer.strip().splitlines():
        line = line.strip()
        if line.upper().startswith("SUFFICIENT"):
            is_sufficient = "YES" in line.upper()
        elif line.upper().startswith("ELEMENT"):
            parts = line.split(":", 1)
            if len(parts) == 2:
                value = parts[1].strip().strip('"').strip("«»")
                if value and value.upper() != "NONE":
                    element_text = value
        elif line.upper().startswith("ZOOM_REGION"):
            parts = line.split(":", 1)
            if len(parts) == 2:
                value = parts[1].strip().lower()
                if value in ZOOM_REGIONS:
                    zoom_region = value
    return is_sufficient, element_text, zoom_region


# Доли viewport'а (x_start, y_start, x_end, y_end) как коэффициенты
# 0..1 для каждой зоны - используется, чтобы вырезать увеличенную
# область скриншота через page.screenshot(clip=...). Универсально для
# любой темы: календарь погоды, таблица характеристик, любая сетка.
ZOOM_REGIONS = {
    "top_left":       (0.0, 0.0, 0.5, 0.33),
    "top_center":     (0.25, 0.0, 0.75, 0.33),
    "top_right":      (0.5, 0.0, 1.0, 0.33),
    "middle_left":    (0.0, 0.33, 0.5, 0.66),
    "middle_center":  (0.25, 0.33, 0.75, 0.66),
    "middle_right":   (0.5, 0.33, 1.0, 0.66),
    "bottom_left":    (0.0, 0.66, 0.5, 1.0),
    "bottom_center":  (0.25, 0.66, 0.75, 1.0),
    "bottom_right":   (0.5, 0.66, 1.0, 1.0),
}


def capture_zoomed_region(page, zoom_region: str, save_path: str) -> bool:
    """Делает увеличенный скриншот указанной зоны текущего viewport'а
    (через клип по пикселям) - та же самая ячейка календаря/таблицы,
    но теперь занимает БОЛЬШУЮ часть кадра, а не крошечный кусочек
    среди всего остального контента, что должно улучшить точность
    распознавания мелких деталей (числа, иконки, короткие подписи).
    Универсально для любой темы, не привязано к конкретной вёрстке."""
    if zoom_region not in ZOOM_REGIONS:
        return False
    x0, y0, x1, y1 = ZOOM_REGIONS[zoom_region]
    vw = page.viewport_size["width"]
    vh = page.viewport_size["height"]
    clip = {
        "x": x0 * vw, "y": y0 * vh,
        "width": (x1 - x0) * vw, "height": (y1 - y0) * vh,
    }
    try:
        page.screenshot(path=save_path, clip=clip)
        return True
    except Exception as e:
        log(f"Не удалось сделать увеличенный скриншот зоны {zoom_region}: {e}")
        return False

